#!/usr/bin/env node
/**
 * ═══════════════════════════════════════════════════════════════
 *  OSIRIS — Wiki Loop Runner
 *
 *  Drives one pass of the intel-wiki refresh loop. Intended for a
 *  scheduler (cron / CI) as much as for a human.
 *
 *  Usage:
 *    npm run wiki -- [options]
 *    node --import ./tools/wiki/src/register.mjs tools/wiki/src/run.ts [options]
 *
 *    --provider gemini|mock   Model backend. Default gemini.
 *    --model <id>             Gemini model id. Default gemini-2.0-flash.
 *    --dir <path>             Wiki directory. Default content/wiki.
 *    --topics <path>          JSON file of Topic[]. Default: derive from --context.
 *    --context <path>         JSON IntelligenceContext to derive topics from.
 *    --ttl-hours <n>          Regenerate entries older than this. Default 24.
 *    --limit <n>              Max topics regenerated this run. Default 10.
 *    --max-steps <n>          Per-topic provider round-trips. Default 4.
 *    --dry-run                Select topics and report, but call nothing.
 *    --json                   Emit the run report as JSON.
 *
 *  Exit codes: 0 ok · 1 usage/config error · 2 one or more topics failed.
 * ═══════════════════════════════════════════════════════════════
 */

import { readFile } from 'node:fs/promises';
import { GeminiProvider, MockProvider, type Provider } from '@/lib/llm';
import { WikiStore, deriveTopics, runWikiLoop, type LoopReport, type Topic } from '@/lib/wiki';
import type { IntelligenceContext } from '@/lib/ai-engine';

interface Options {
  provider: 'gemini' | 'mock';
  model: string;
  dir: string;
  topicsPath?: string;
  contextPath?: string;
  ttlHours: number;
  limit: number;
  maxSteps: number;
  dryRun: boolean;
  json: boolean;
}

class UsageError extends Error {}

function parseArgs(argv: string[]): Options {
  const options: Options = {
    provider: 'gemini',
    model: 'gemini-2.0-flash',
    dir: 'content/wiki',
    ttlHours: 24,
    limit: 10,
    maxSteps: 4,
    dryRun: false,
    json: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = (): string => {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) throw new UsageError(`${arg} needs a value.`);
      i += 1;
      return value;
    };

    switch (arg) {
      case '--provider': {
        const value = next();
        if (value !== 'gemini' && value !== 'mock') throw new UsageError('--provider must be gemini or mock.');
        options.provider = value;
        break;
      }
      case '--model': options.model = next(); break;
      case '--dir': options.dir = next(); break;
      case '--topics': options.topicsPath = next(); break;
      case '--context': options.contextPath = next(); break;
      case '--ttl-hours': options.ttlHours = numeric(next(), '--ttl-hours'); break;
      case '--limit': options.limit = numeric(next(), '--limit'); break;
      case '--max-steps': options.maxSteps = numeric(next(), '--max-steps'); break;
      case '--dry-run': options.dryRun = true; break;
      case '--json': options.json = true; break;
      case '--help':
      case '-h': throw new UsageError('help');
      default: throw new UsageError(`Unknown flag: ${arg}`);
    }
  }
  return options;
}

function numeric(raw: string, flag: string): number {
  const value = Number(raw);
  if (!Number.isFinite(value) || value <= 0) throw new UsageError(`${flag} must be a positive number.`);
  return value;
}

async function loadTopics(options: Options): Promise<Topic[]> {
  if (options.topicsPath) {
    return JSON.parse(await readFile(options.topicsPath, 'utf8')) as Topic[];
  }
  if (options.contextPath) {
    const context = JSON.parse(await readFile(options.contextPath, 'utf8')) as IntelligenceContext;
    return deriveTopics(context);
  }
  throw new UsageError('Supply --topics <file> or --context <file>.');
}

function buildProvider(options: Options): Provider {
  if (options.provider === 'mock') {
    // Offline smoke path: exercises selection, writing and reporting end to end.
    return new MockProvider({
      script: [
        {
          kind: 'text',
          text: JSON.stringify({
            title: 'Mock entry',
            summary: 'Generated by the mock provider for a dry local run of the loop.',
            body: '## Observed\nNothing — this entry came from the mock provider.\n\n## Assessment\nNot intelligence.',
            tags: ['mock'],
            confidence: 'low',
            sources: [],
          }),
        },
      ],
    });
  }

  const apiKey = process.env.GEMINI_API_KEY ?? process.env.GOOGLE_API_KEY;
  if (!apiKey) throw new UsageError('Set GEMINI_API_KEY (or GOOGLE_API_KEY), or pass --provider mock.');
  return new GeminiProvider({ apiKey, model: options.model });
}

function render(report: LoopReport): void {
  const line = (label: string, value: string | number): void => {
    process.stdout.write(`${label.padEnd(12)}: ${value}\n`);
  };

  line('considered', report.considered);
  line('selected', report.selected);
  line('created', report.created);
  line('updated', report.updated);
  line('unchanged', report.unchanged);
  line('skipped', report.skipped);
  line('failed', report.failed);
  line('cost', `$${report.costUsd.toFixed(4)}`);
  line('duration', `${report.durationMs}ms`);

  if (report.outcomes.length > 0) {
    process.stdout.write('\n');
    for (const outcome of report.outcomes) {
      const detail = outcome.reason ? ` — ${outcome.reason}` : outcome.revision ? ` — rev ${outcome.revision}` : '';
      process.stdout.write(`  ${outcome.status.padEnd(10)} ${outcome.slug}${detail}\n`);
    }
  }
}

const HELP = `osiris wiki loop runner

  npm run wiki -- --context intel.json [--dry-run] [--json]
  npm run wiki -- --topics topics.json --provider mock

See the header of tools/wiki/src/run.ts for the full flag list.`;

export async function main(argv: string[]): Promise<number> {
  let options: Options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    if (error instanceof UsageError && error.message === 'help') {
      process.stdout.write(`${HELP}\n`);
      return 0;
    }
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }

  try {
    const topics = await loadTopics(options);
    const report = await runWikiLoop({
      store: new WikiStore({ dir: options.dir }),
      provider: buildProvider(options),
      topics,
      policy: { ttlMs: options.ttlHours * 60 * 60 * 1000 },
      maxTopicsPerRun: options.limit,
      limits: { maxSteps: options.maxSteps },
      dryRun: options.dryRun,
    });

    if (options.json) process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
    else render(report);

    return report.failed > 0 ? 2 : 0;
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error: unknown) => {
      process.stderr.write(`Fatal: ${error instanceof Error ? error.message : String(error)}\n`);
      process.exitCode = 1;
    },
  );
}
